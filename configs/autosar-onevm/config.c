#define SINGLE_VM_IRQ_NUM (sizeof(single_vm_irqs) / sizeof(single_vm_irqs[0]))

struct config config = {

    /*
     * Bao's .data/.bss default to the first RWX region (Cluster0 at
     * 0xFE000000), which is exactly the guest's main RAM. Relocate to
     * Cluster1, the one RAM block this guest never touches.
     */
    .hyp = {
        .data_relocate = true,
        .data_addr = 0xFE100000,
    },

    .vmlist_size = 1,
    .vmlist = (struct vm_config[]){
        {
            .entry = 0x10000,
            .image = VM_IMAGE_LOADED(0x10000, 0x10000, 0x400000),
            .cpu_affinity = 0xF, /* PE0..PE3 */

            .platform = {
                .cpu_num = 4,

                .region_num = 4,
                .regions = (struct vm_mem_region[]){
                    /* Guest code window: iROM_0 at 0x10000 plus dBaseROM,
                     * which the HV linker layout puts at 0x400000 so that one
                     * window covers exactly what the guest uses. */
                    { .base = 0x00010000, .size = 0x400000 },
                    /* Cluster0 RAM -- .data/.bss, PE0 stack, OS system stacks */
                    { .base = 0xFE000000, .size = 0x80000 },
                    /* Cluster2 RAM -- ETH_PORT_RAM_1, RAM_WDGM, RAM_CAL */
                    { .base = 0xFE400000, .size = 0x80000 },
                    /* Retention RAM -- .rcode */
                    { .base = 0xFE800000, .size = 0x20000 },
                },

                .dev_num = 12,
                .devs = (struct vm_dev_region[]){
                    /* Local RAM: the four per-PE views and the self alias.
                     * The self alias at 0xFDE00000 is where .Os_Clone lives --
                     * every PE sees its own local RAM at that one address. */
                    { .pa = 0xFD600000, .va = 0xFD600000, .size = 0x10000,
                      .interrupt_num = 0, .interrupts = NULL, },
                    { .pa = 0xFD800000, .va = 0xFD800000, .size = 0x10000,
                      .interrupt_num = 0, .interrupts = NULL, },
                    { .pa = 0xFDA00000, .va = 0xFDA00000, .size = 0x10000,
                      .interrupt_num = 0, .interrupts = NULL, },
                    { .pa = 0xFDC00000, .va = 0xFDC00000, .size = 0x10000,
                      .interrupt_num = 0, .interrupts = NULL, },
                    { .pa = 0xFDE00000, .va = 0xFDE00000, .size = 0x10000,
                      .interrupt_num = 0, .interrupts = NULL, },

                    /* The peripheral space, swept. Each entry runs up to the
                     * next thing Bao emulates and resumes just past it; the
                     * comment on each gap names what is being skipped. */

                    /* .. up to INTIF */
                    { .pa = 0xFF000000, .va = 0xFF000000, .size = 0x00090000,
                      .interrupt_num = SINGLE_VM_IRQ_NUM,
                      .interrupts = single_vm_irqs, },
                    /* INTIF 0xFF090000 emulated */
                    { .pa = 0xFF090240, .va = 0xFF090240, .size = 0x009137C0,
                      .interrupt_num = 0, .interrupts = NULL, },
                    /* FENC 0xFF9A3A00 emulated; resume right after it.
                     *
                     * ★ The four FEINC blocks at 0xFF9A3B00..0xFF9A3EFF are
                     * NOT holes, even though Bao registers an emulator for
                     * them: the guest OS masks FEINT during init and that has
                     * to reach the real registers. The verified configuration
                     * passes the whole 0x400 range through for exactly this
                     * reason, and punching holes here was what stopped the
                     * guest dead.
                     *
                     * So "Bao emulates it" is not the test for whether to leave
                     * a window out. The test is whether the emulation actually
                     * serves the guest; where it does not, the passthrough
                     * mapping shadows the handler and that is deliberate. */
                    { .pa = 0xFF9A3A40, .va = 0xFF9A3A40, .size = 0x0025C5C0,
                      .interrupt_num = 0, .interrupts = NULL, },
                    /* EINT 0xFFC00000 emulated; then on to INTC2 */
                    { .pa = 0xFFC00040, .va = 0xFFC00040, .size = 0x0037FFC0,
                      .interrupt_num = 0, .interrupts = NULL, },
                    /* INTC2 0xFFF80000..0xFFF87FFF emulated -- the one that
                     * matters most. Mapping it would hand the guest the routing
                     * table Bao depends on.
                     *
                     * ★ The size here is the manual's (32 KB, section 4 address
                     * map), not sizeof(struct intc2) rounded up. Deriving it
                     * from the struct gave 0x6000 and left the last 8 KB of
                     * INTC2 passed through -- EIBD and EEIC live in there, so
                     * the guest reprogrammed routing behind vintc's back and
                     * nothing worked. Take peripheral extents from the manual. */
                    { .pa = 0xFFF88000, .va = 0xFFF88000, .size = 0x0002A000,
                      .interrupt_num = 0, .interrupts = NULL, },
                    /* BOOTCTRL 0xFFFB2000 emulated -- Bao starts the secondary
                     * vcpus when the guest writes it */
                    { .pa = 0xFFFB2040, .va = 0xFFFB2040, .size = 0x00006FC0,
                      .interrupt_num = 0, .interrupts = NULL, },
                    /* IPIR 0xFFFB9000..0xFFFBAFFF emulated -- the hole runs
                     * to the next thing the manual names (TPTM at 0xFFFBB000)
                     * rather than to the end of sizeof(struct ipir_hw), which
                     * would stop at 0xFFFB9BFF and pass the rest of the block
                     * through. Same mistake as the INTC2 one above: take the
                     * extent from the manual, not from the emulation struct. */
                    { .pa = 0xFFFBB000, .va = 0xFFFBB000, .size = 0x00045000,
                      .interrupt_num = 0, .interrupts = NULL, },
                },
            },
        },
    },
};
