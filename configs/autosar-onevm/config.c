/*
 * ⚠ WORK IN PROGRESS -- does not boot. Kept for the next attempt.
 *
 * The idea is right for a single VM: sweep the whole peripheral space in a few
 * windows instead of naming devices one at a time, which is how autosar-onevm
 * came to cover a fifth of the manual's peripheral regions. Eleven windows here
 * against nineteen there, and they cover everything.
 *
 * What is known so far. The interrupt half of this file is fine and now lives
 * in autosar-onevm, board-verified. The mapping half stops the guest dead with
 * no CAN and no console. One cause was found and fixed and did not account for
 * it: INTC2 is 32 KB by the manual's address map, while deriving the size from
 * sizeof(struct intc2) gave 0x6000 and left its last 8 KB -- EIBD and EEIC --
 * passed through, so the guest could reprogram routing behind vintc. Take
 * peripheral extents from the manual, never from the emulation struct.
 *
 * Still to find: what else in the sweep breaks it. Bisect the windows, and get
 * a readable console first -- every round of this cost four minutes and told us
 * only "no frames", which is the same answer for every cause.
 */

/*
 * RH850/U2A16 -- the whole four-core AUTOSAR project as one VM.
 *
 * With a single VM there is nothing to partition, so this configuration is not
 * trying to divide the machine: it is trying to stay out of the way. The guest
 * gets the entire peripheral address space and every interrupt the device has,
 * and the hypervisor keeps only what it cannot share.
 *
 * That is a deliberate change of shape. The configuration this replaces was
 * assembled one block at a time across seventy board rounds, each round adding
 * whatever the guest had just died on, and it ended up covering less than a
 * fifth of the peripheral regions in the manual with eleven interrupts named
 * out of seven hundred. Every one of those gaps failed the same way -- silently
 * -- because an unmapped peripheral aborts somewhere far from the cause and an
 * unassigned interrupt is dropped by the emulated INTC without a word.
 *
 * The previous configuration is kept, buildable, as autosar-onevm-minimal.
 *
 * ---- memory ---------------------------------------------------------------
 * Four RAM regions plus the guest's flash window, as before.
 *
 * ---- peripherals ----------------------------------------------------------
 * One sweep of 0xFF000000..0xFFFFFFFF, minus the ten holes Bao has to keep for
 * itself. The holes are not optional: a device that Bao emulates must NOT be
 * mapped, because a mapped region never traps and the emulation would simply
 * never run. INTC2 is the sharpest of these -- passing it through would let the
 * guest reprogram interrupt routing behind the hypervisor's back, including the
 * lines Bao uses.
 *
 * Eleven windows where the old configuration used nineteen, and they cover
 * everything instead of a fifth of it.
 *
 * ---- interrupts -----------------------------------------------------------
 * All 701 assignable channels, generated by scripts/gen_irqs.py from the
 * manual's own interrupt table. Reserved channels are left out because
 * intc_vm_assign writes EIBD for every id it is handed and those have no
 * register; channel 3 is left out because it is the hypervisor's IPI and
 * vm_init_dev turns a refused assignment into a fatal error.
 */

